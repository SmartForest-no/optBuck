# ==============================================================================
# scripts/98_create_github_safe_processed_data.R
#
# Purpose : Create a sanitized copy of selected data_processed/ files that
#           can be committed to the private GitHub repository.
#
# Policy  : Processed NFI-derived data may be included in the private repo
#           only if precise sample-plot coordinates and original plot
#           identifiers are not included.
#           - No exact spatial coordinate columns (none were found).
#           - Original plot_id (indirect NFI locator) is replaced by a
#             synthetic sequential identifier: plot_id_github.
#           - The mapping between original and synthetic IDs is created
#             temporarily inside this script and is NOT written to disk.
#
# Coordinate column findings (2026-07-01):
#   No explicit spatial coordinate columns (x, y, lat, lon, UTM, easting,
#   northing, etc.) exist in any source parquet file.
#   Location-adjacent columns and disposition:
#     plot_id         REPLACED with plot_id_github (indirect NFI locator)
#     flateid         DROPPED  (same value as plot_id; indirect locator)
#     flatenr         DROPPED  (all values = 1; no informational content)
#     hel_delt_flate  DROPPED  (all values = 0; no informational content)
#     komnr           DROPPED  (municipality code; finer than needed)
#     fylnr           KEPT     (county code; coarse administrative unit)
#     hoh             KEPT     (elevation metres integer; coarse; not a coord)
#   No projected-coordinate rounding was applied (no such columns present).
#
# Synthetic plot_id_github:
#   - Generated by sorting unique original plot_id values alphabetically.
#   - Assigned sequential identifiers: P000001, P000002, ...
#   - Deterministic across runs given the same source data.
#   - Group membership (which trees belong to which plot) is preserved.
#   - The mapping is never written to data_processed_github/ or committed.
#
# Files produced in data_processed_github/:
#   nfi_tree_plot_stratum_ready_github.parquet   (main backend file)
#   nfi_plots_github.parquet                     (plot metadata for app UI)
#   sanitization_manifest.txt                    (audit log for this run)
#
# Files NOT included (not needed by the sampled-plot backend):
#   nfi_trees_2024_spruce_pine            (subset of stratum_ready; skip)
#   nfi_tree_plot_2024_spruce_pine        (superseded by stratum_ready; skip)
#   All .rds variants                     (parquet versions sufficient)
#
# Usage:
#   Rscript scripts/98_create_github_safe_processed_data.R
#   Source interactively from project root.
#
# Safety:
#   This script NEVER overwrites data_processed/.
#   Outputs go exclusively to data_processed_github/.
#   The plot_id <-> plot_id_github mapping is ephemeral (in-memory only).
# ==============================================================================

suppressPackageStartupMessages({
  library(arrow)
  library(dplyr)
})

# ---- paths -------------------------------------------------------------------
ROOT     <- local({
  # APTER_ROOT -> walk up from getwd() -> stop()
  is_root <- function(d) file.exists(file.path(d, "R", "helpers_paths.R"))
  env <- Sys.getenv("APTER_ROOT", unset = "")
  if (nzchar(env)) {
    d <- normalizePath(env, winslash = "/", mustWork = FALSE)
    if (!is_root(d))
      stop("Project root '", d, "' (from APTER_ROOT) does not contain ",
           "R/helpers_paths.R.", call. = FALSE)
  } else {
    d <- normalizePath(getwd(), winslash = "/", mustWork = FALSE)
    while (!is_root(d) && dirname(d) != d) d <- dirname(d)
    if (!is_root(d))
      stop("Cannot locate the project root: set APTER_ROOT, or run from ",
           "inside the project directory.", call. = FALSE)
  }
  d
})
SRC_DIR  <- file.path(ROOT, "data_processed")
OUT_DIR  <- file.path(ROOT, "data_processed_github")
MANIFEST <- file.path(OUT_DIR, "sanitization_manifest.txt")
RUN_TIME <- format(Sys.time(), "%Y-%m-%d %H:%M:%S")

if (!dir.exists(SRC_DIR)) stop("data_processed/ not found at: ", SRC_DIR)
if (!dir.exists(OUT_DIR)) dir.create(OUT_DIR, recursive = TRUE)

# ---- columns to DROP (applies to all files) ----------------------------------
# These columns are direct or indirect NFI plot locators, or carry no analytic
# value. They must never appear in data_processed_github/.
ALWAYS_DROP <- c(
  "plot_id",        # original NFI plot ID -- REPLACED by plot_id_github
  "flateid",        # same as plot_id; indirect locator
  "flatenr",        # plot sub-number (all = 1; no utility)
  "hel_delt_flate", # full/partial flag (all = 0; no utility)
  "komnr"           # municipality code (finer resolution than needed)
)

# ---- columns to KEEP in the tree+plot file -----------------------------------
# Ordered list; plot_id_github will be prepended after ID assignment.
KEEP_TREE_PLOT <- c(
  "treid",          # individual tree ID within plot (required by optimizer)
  "sesong",         # survey season/year (provenance)
  "species_group",  # "spruce" / "pine" (stratum filter; taper input)
  "dbh_cm",         # DBH in cm (taper profile input)
  "trehoyde",       # measured tree height m (taper input; may be NA)
  "beregnet_hoyde", # model-calculated height m (taper fallback input)
  "tilstand",       # tree condition code (alive/dead filter)
  "volm",           # stem volume with bark m3 (reference comparison)
  "volu",           # stem volume without bark m3 (reference comparison)
  "hogstkl",        # maturity class (stratum filter)
  "abonitet",       # site quality class (stratum filter)
  "fylnr",          # county code -- coarse location (optional filter; KEPT)
  "hoh",            # elevation m -- coarse (optional filter; KEPT)
  "plot_area_m2"    # plot area (per-ha scaling in app)
)

# Dropped from tree+plot (beyond ALWAYS_DROP):
#   treslag    -- raw species code; species_group derived, sufficient
#   brysth_dia -- raw DBH mm; dbh_cm derived, sufficient
#   tslgr      -- tree class code; not needed by optimizer
#   tilv5      -- 5-year volume increment; not needed
#   abonitet_tre -- tree-level site index; plot-level abonitet sufficient
#   best_tresl -- plot dominant species; not needed
#   gran_pr / furu_pr / bjork_pr -- species proportions; not needed
#   arealtype / areal_anv        -- land use; not needed
#   lsk_dato                     -- survey date; not needed

# ---- columns to KEEP in the plots file ---------------------------------------
KEEP_PLOTS <- c(
  "sesong",       # survey season
  "hogstkl",      # maturity class (stratum filter)
  "abonitet",     # site quality class (stratum filter)
  "fylnr",        # county code (coarse location; optional filter)
  "hoh",          # elevation m (coarse; optional filter)
  "plot_area_m2"  # plot area (per-ha scaling)
)

# ==============================================================================
# Step 1: Build the synthetic plot_id mapping
# This mapping lives only in memory and is never written to disk.
# ==============================================================================
cat("Building synthetic plot_id_github mapping...\n")

src_stratum <- file.path(SRC_DIR,
                          "nfi_tree_plot_2024_spruce_pine_stratum_ready.parquet")
src_plots   <- file.path(SRC_DIR, "nfi_plots_2024.parquet")

# Collect the sorted unique original plot_ids from the stratum-ready file
# (the primary file; plots file is a subset so shares the same IDs)
orig_plot_ids <- open_dataset(src_stratum) |>
  select(plot_id) |>
  collect() |>
  distinct(plot_id) |>
  arrange(plot_id) |>
  pull(plot_id)

n_plots <- length(orig_plot_ids)
cat("  Unique original plot_ids:", n_plots, "\n")

# Assign deterministic sequential synthetic IDs: P000001, P000002, ...
synthetic_ids <- sprintf("P%06d", seq_len(n_plots))

# Build in-memory lookup (data.frame, never written to disk)
id_map <- data.frame(
  plot_id        = orig_plot_ids,
  plot_id_github = synthetic_ids,
  stringsAsFactors = FALSE
)

cat("  Synthetic IDs: P000001 to", tail(synthetic_ids, 1), "\n")
cat("  IMPORTANT: mapping is in-memory only -- not written to disk.\n\n")

# ==============================================================================
# Step 2: Sanitize nfi_tree_plot_2024_spruce_pine_stratum_ready.parquet
# ==============================================================================
out_file_1 <- file.path(OUT_DIR, "nfi_tree_plot_stratum_ready_github.parquet")
cat("Processing:", basename(src_stratum), "\n")

ds1      <- open_dataset(src_stratum)
src_cols_1 <- names(ds1)

# Check that every KEEP column is actually present
missing_1 <- setdiff(KEEP_TREE_PLOT, src_cols_1)
if (length(missing_1) > 0) {
  warning("KEEP columns not found in source (skipped): ",
          paste(missing_1, collapse = ", "))
  KEEP_TREE_PLOT <- intersect(KEEP_TREE_PLOT, src_cols_1)
}

df1 <- ds1 |>
  select(plot_id, all_of(KEEP_TREE_PLOT)) |>   # keep original plot_id for join
  collect() |>
  left_join(id_map, by = "plot_id") |>          # attach synthetic ID
  select(plot_id_github, all_of(KEEP_TREE_PLOT)) # drop original; synthetic first

# Safety check: no original identifiers must remain
bad_cols_1 <- intersect(names(df1), ALWAYS_DROP)
if (length(bad_cols_1) > 0) {
  stop("SAFETY FAIL: original identifier columns still present in tree_plot output: ",
       paste(bad_cols_1, collapse = ", "))
}

write_parquet(df1, out_file_1)
final_cols_1 <- names(df1)
cat("  Written:", basename(out_file_1),
    "(", nrow(df1), "rows,", length(final_cols_1), "cols)\n")
cat("  Unique plot_id_github:", length(unique(df1$plot_id_github)), "\n")

dropped_1 <- setdiff(src_cols_1, c("plot_id", KEEP_TREE_PLOT))

# ==============================================================================
# Step 3: Sanitize nfi_plots_2024.parquet
# ==============================================================================
out_file_2 <- file.path(OUT_DIR, "nfi_plots_github.parquet")
cat("\nProcessing:", basename(src_plots), "\n")

ds2      <- open_dataset(src_plots)
src_cols_2 <- names(ds2)

missing_2 <- setdiff(KEEP_PLOTS, src_cols_2)
if (length(missing_2) > 0) {
  warning("KEEP columns not found in source (skipped): ",
          paste(missing_2, collapse = ", "))
  KEEP_PLOTS <- intersect(KEEP_PLOTS, src_cols_2)
}

df2 <- ds2 |>
  select(plot_id, all_of(KEEP_PLOTS)) |>
  collect() |>
  # Keep only plots that have spruce/pine trees in the stratum-ready file.
  # Plots with no qualifying trees are not relevant to the app backend and
  # would produce NA plot_id_github (they are absent from the id_map).
  filter(plot_id %in% id_map$plot_id) |>
  left_join(id_map, by = "plot_id") |>
  select(plot_id_github, all_of(KEEP_PLOTS))

# Safety check
bad_cols_2 <- intersect(names(df2), ALWAYS_DROP)
if (length(bad_cols_2) > 0) {
  stop("SAFETY FAIL: original identifier columns still present in plots output: ",
       paste(bad_cols_2, collapse = ", "))
}

write_parquet(df2, out_file_2)
final_cols_2 <- names(df2)
cat("  Written:", basename(out_file_2),
    "(", nrow(df2), "rows,", length(final_cols_2), "cols)\n")
cat("  Unique plot_id_github:", length(unique(df2$plot_id_github)), "\n")

dropped_2 <- setdiff(src_cols_2, c("plot_id", KEEP_PLOTS))

# ==============================================================================
# Step 4: Write sanitization manifest
# ==============================================================================
manifest_lines <- c(
  "Apter -- data_processed_github/ sanitization manifest",
  paste("Run time    :", RUN_TIME),
  paste("Source      :", SRC_DIR),
  paste("Destination :", OUT_DIR),
  "",
  "=== Privacy policy applied ===",
  "  This data was sanitized for inclusion in the private GitHub repository.",
  "  All estimates derived from this data are SAMPLED ESTIMATES only.",
  "  No NFI expansion factors have been applied.",
  "  No exact plot locations are included.",
  "",
  "=== Coordinate column inspection ===",
  "  Result: NO explicit spatial coordinate columns were found in any source",
  "  parquet file (no x, y, lat, lon, easting, northing, UTM, etc.).",
  "",
  "=== Original plot identifier handling ===",
  "  Original plot_id (e.g. 'E25159') is an NFI plot code that could be",
  "  reverse-looked-up to an exact sample-plot location in the NFI database.",
  "  Action taken: original plot_id REPLACED by synthetic plot_id_github.",
  "  Synthetic format: P000001, P000002, ... (sorted alphabetically by original).",
  "  The mapping between original and synthetic IDs was created in-memory only",
  "  and was NOT written to disk or committed to the repository.",
  paste("  Number of unique original plot_ids replaced:", n_plots),
  "",
  "=== Column disposition summary ===",
  "  REPLACED: plot_id       -> plot_id_github (synthetic sequential ID)",
  "  DROPPED:  flateid       (same value as original plot_id; indirect locator)",
  "  DROPPED:  flatenr       (all values = 1; no informational content)",
  "  DROPPED:  hel_delt_flate (all values = 0; no informational content)",
  "  DROPPED:  komnr         (municipality code; finer resolution than needed)",
  "  KEPT:     fylnr         (county code; coarse administrative unit)",
  "  KEPT:     hoh           (elevation metres integer; coarse; not a coordinate)",
  "",
  "=== File 1: nfi_tree_plot_stratum_ready_github.parquet ===",
  paste("  Source   :", basename(src_stratum)),
  paste("  Rows     :", nrow(df1)),
  paste("  Unique plots (plot_id_github):", length(unique(df1$plot_id_github))),
  paste("  Cols kept (", length(final_cols_1), "):",
        paste(final_cols_1, collapse = ", ")),
  paste("  Cols dropped (", length(dropped_1) + 1L, ", including original plot_id):",
        paste(c("plot_id", dropped_1), collapse = ", ")),
  "",
  "=== File 2: nfi_plots_github.parquet ===",
  paste("  Source   :", basename(src_plots)),
  paste("  Rows     :", nrow(df2)),
  paste("  Unique plots (plot_id_github):", length(unique(df2$plot_id_github))),
  paste("  Cols kept (", length(final_cols_2), "):",
        paste(final_cols_2, collapse = ", ")),
  paste("  Cols dropped (", length(dropped_2) + 1L, ", including original plot_id):",
        paste(c("plot_id", dropped_2), collapse = ", ")),
  "",
  "=== Files intentionally NOT included ===",
  "  nfi_trees_2024_spruce_pine.parquet/.rds  (subset of stratum_ready; skip)",
  "  nfi_tree_plot_2024_spruce_pine.parquet/.rds  (superseded by stratum_ready)",
  "  All .rds variants  (parquet versions sufficient)",
  "  plot_id <-> plot_id_github mapping  (NEVER written; in-memory only)",
  "",
  "=== Safety verification ===",
  paste("  'plot_id' absent from tree_plot output  :",
        !"plot_id" %in% names(df1)),
  paste("  'plot_id' absent from plots output      :",
        !"plot_id" %in% names(df2)),
  paste("  'flateid' absent from tree_plot output  :",
        !"flateid" %in% names(df1)),
  paste("  'flateid' absent from plots output      :",
        !"flateid" %in% names(df2)),
  paste("  'komnr' absent from tree_plot output    :",
        !"komnr" %in% names(df1)),
  paste("  'komnr' absent from plots output        :",
        !"komnr" %in% names(df2)),
  paste("  'plot_id_github' present in both outputs:",
        "plot_id_github" %in% names(df1) && "plot_id_github" %in% names(df2))
)

writeLines(manifest_lines, MANIFEST)
cat("\nManifest written to:", MANIFEST, "\n")
cat("\nSanitization complete. Outputs in:", OUT_DIR, "\n")
cat("REMINDER: verify with\n")
cat("  git ls-files --others --exclude-standard data_processed_github/\n")
